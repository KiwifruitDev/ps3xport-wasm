// Builds the ps3xport WebAssembly core with Emscripten.
//
// Usage:
//   node scripts/build-wasm.mjs [--debug] [--emcc <path>]
//
// The build writes web/ps3xport.mjs and web/ps3xport.wasm and a generated
// header that embeds src/core/keys.conf into the wasm binary.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const coreDir = join(projectRoot, 'src', 'core');
const wasmDir = join(projectRoot, 'src', 'wasm');
const buildDir = join(projectRoot, 'build');
const genDir = join(buildDir, 'generated');
const webDir = join(projectRoot, 'web');

const args = process.argv.slice(2);
const debug = args.includes('--debug');
const emccOption = args.indexOf('--emcc');

function fail(message) {
  console.error(message);
  process.exit(1);
}

function findEmcc() {
  const candidates = [];
  if (emccOption !== -1 && args[emccOption + 1]) {
    candidates.push(args[emccOption + 1]);
  }
  if (process.env.EMCC) candidates.push(process.env.EMCC);
  for (const sdk of [process.env.EMSDK, join(process.env.USERPROFILE ?? '', 'emsdk'), join(process.env.HOME ?? '', 'emsdk')]) {
    if (!sdk) continue;
    candidates.push(join(sdk, 'upstream', 'emscripten', 'emcc.exe'));
    candidates.push(join(sdk, 'upstream', 'emscripten', 'emcc'));
    candidates.push(join(sdk, 'upstream', 'emscripten', 'emcc.bat'));
  }
  candidates.push('emcc');
  for (const candidate of candidates) {
    if (candidate === 'emcc') {
      try {
        execFileSync('emcc', ['--version'], { stdio: 'ignore' });
        return 'emcc';
      } catch {
        continue;
      }
    }
    if (existsSync(candidate)) return candidate;
  }
  return null;
}

const emcc = findEmcc();
if (!emcc) {
  fail('Emscripten was not found. Install the Emscripten SDK and set EMSDK, or pass --emcc <path to emcc>.');
}

mkdirSync(genDir, { recursive: true });

// Embed keys.conf so the browser never needs the user to supply it.
const keysConf = readFileSync(join(coreDir, 'keys.conf'));
const hex = keysConf.toString('hex');
const rows = [];
for (let i = 0; i < hex.length; i += 64) {
  const slice = hex.slice(i, i + 64);
  const bytes = slice.match(/../g).map(byte => `0x${byte}`).join(', ');
  rows.push(`  ${bytes},`);
}
writeFileSync(join(genDir, 'keys_conf_blob.h'), `/* Generated by scripts/build-wasm.mjs - do not edit. */
#ifndef PX_KEYS_CONF_BLOB_H
#define PX_KEYS_CONF_BLOB_H

static const unsigned char px_keys_conf[] = {
${rows.join('\n')}
};

static const unsigned int px_keys_conf_len = ${keysConf.length}u;

#endif
`);

const sources = [
  'aes.c',
  'sha1.c',
  'tools.c',
  'keys.c',
  'paged_file.c',
  'archive.c',
  'vtrm.c',
].map(name => join(coreDir, name));
sources.push(join(wasmDir, 'api.c'));

const exportedFunctions = [
  '_malloc',
  '_free',
  '_px_init',
  '_px_last_error',
  '_px_errno',
  '_px_set_device_id',
  '_px_set_open_psid',
  '_px_index_open',
  '_px_index_close',
  '_px_index_file_count',
  '_px_index_file_path',
  '_px_index_file_size',
  '_px_index_file_mode',
  '_px_index_file_mtime',
  '_px_index_dir_count',
  '_px_index_dir_path',
  '_px_index_dir_mode',
  '_px_index_total_files',
  '_px_index_total_file_sizes',
  '_px_index_total_dirs',
  '_px_index_archive2_size',
  '_px_index_archive_type',
  '_px_index_id',
  '_px_index_psid',
  '_px_probe_dat',
  '_px_data_read',
  '_px_data_id',
  '_px_data_index',
  '_px_data_archive_type',
  '_px_data_file_type',
  '_px_extract_file',
  '_px_extract_all',
  '_px_extract_path',
  '_px_decrypt',
  '_px_create_backup',
  '_px_add',
  '_px_delete_file',
  '_px_delete_path',
  '_px_delete_protected',
];

const flags = [
  '-std=gnu11',
  debug ? '-O0' : '-O2',
  debug ? '-g' : '',
  '-DPS3XPORT_WASM=1',
  `-I${coreDir}`,
  `-I${wasmDir}`,
  `-I${genDir}`,
  '--no-entry',
  '-sMODULARIZE=1',
  '-sEXPORT_ES6=1',
  '-sEXPORT_NAME=createPs3xportModule',
  '-sENVIRONMENT=web,worker,node',
  '-sALLOW_MEMORY_GROWTH=1',
  '-sINITIAL_MEMORY=33554432',
  '-sSTACK_SIZE=1048576',
  '-sFILESYSTEM=1',
  '-sFORCE_FILESYSTEM=1',
  `-sEXPORTED_FUNCTIONS=${exportedFunctions.join(',')}`,
  '-sEXPORTED_RUNTIME_METHODS=FS,ccall,cwrap,UTF8ToString,stringToUTF8,lengthBytesUTF8,ERRNO_CODES',
  `-sASSERTIONS=${debug ? 1 : 0}`,
  '-sSTACK_OVERFLOW_CHECK=' + (debug ? '2' : '0'),
  debug ? '-sSAFE_HEAP=1' : '',
  `-o${join(webDir, 'ps3xport.mjs')}`,
].filter(Boolean);

console.log(`emcc: ${emcc}`);
console.log(`mode: ${debug ? 'debug' : 'release'}`);

try {
  execFileSync(emcc, [...flags, ...sources], {
    stdio: 'inherit',
    cwd: projectRoot,
    env: { ...process.env, EMCC_SKIP_SANITY_CHECK: process.env.EMCC_SKIP_SANITY_CHECK ?? '1' },
  });
} catch (error) {
  fail(`Build failed: ${error.message}`);
}

console.log('Built web/ps3xport.mjs and web/ps3xport.wasm');
